//! P-GOP encoder interop pin.
//!
//! The golden stream below is this crate's deterministic low-delay
//! encode (`IDR + 4 x TRAIL_R P`) of a fixed 5-frame 64x64 clip at
//! `SliceQpY 27`, validated OUT OF BAND against a black-box reference
//! HEVC decoder (which reproduces every frame of the encoder's
//! reconstruction byte-exactly). Re-encoding the same clip must
//! reproduce the golden bytes, and the crate's own decoder must
//! decode them to the encoder's reconstructions — a three-way
//! (encoder recon / this decoder / external reference decoder)
//! bit-exactness pin over skip, merge, AMVP and intra-fallback CUs.
//! If an intentional encoder change breaks this, regenerate the bytes
//! AND re-run the external cross-decode before updating the pin.

use oxideav_h265::decode_annexb_sequence;
use oxideav_h265::encoder::inter::{encode_low_delay_p, YuvFrame};

/// The fixed clip: a textured background with a 12x12 bright square
/// moving 3 px right / 1 px down per frame, chroma drifting per frame.
fn clip(w: usize, h: usize, n: usize) -> Vec<(Vec<u8>, Vec<u8>, Vec<u8>)> {
    (0..n)
        .map(|t| {
            let y: Vec<u8> = (0..w * h)
                .map(|i| {
                    let (x, yy) = (i % w, i / w);
                    let base = (x * 2 + yy * 3) % 200;
                    let (sx, sy) = (4 + t * 3, 6 + t);
                    if x >= sx && x < sx + 12 && yy >= sy && yy < sy + 12 {
                        (base + 55) as u8
                    } else {
                        base as u8
                    }
                })
                .collect();
            let cb: Vec<u8> = (0..w * h / 4)
                .map(|i| (100 + (i % (w / 2)) * 2 % 60 + t) as u8)
                .collect();
            let cr: Vec<u8> = (0..w * h / 4)
                .map(|i| {
                    (160u32.wrapping_sub((i / (w / 2)) as u32 * 2 % 50) as u8).wrapping_sub(t as u8)
                })
                .collect();
            (y, cb, cr)
        })
        .collect()
}

#[test]
fn golden_p_gop_stream_is_reproduced_and_decodes_to_recon() {
    let planes = clip(64, 64, 5);
    let frames: Vec<YuvFrame<'_>> = planes
        .iter()
        .map(|(y, cb, cr)| YuvFrame { y, cb, cr })
        .collect();
    let enc = encode_low_delay_p(&frames, 64, 64, 27).expect("encode");
    assert_eq!(
        enc.stream, GOLDEN_QP27_GOP,
        "deterministic encode reproduces the externally validated golden stream"
    );
    let decoded = decode_annexb_sequence(GOLDEN_QP27_GOP).expect("decode");
    assert_eq!(decoded.len(), 5);
    for (i, (dec, rec)) in decoded.iter().zip(enc.recon.iter()).enumerate() {
        let mut expect = rec.y.clone();
        expect.extend_from_slice(&rec.cb);
        expect.extend_from_slice(&rec.cr);
        assert_eq!(
            dec.picture.to_planar_u8().expect("8-bit"),
            expect,
            "frame {i}: decoder output == encoder reconstruction"
        );
    }
}

