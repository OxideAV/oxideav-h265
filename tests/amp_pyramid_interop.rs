//! AMP + hierarchical-B encoder interop pins.
//!
//! Golden streams for the round-431 encoder axes, each validated OUT
//! OF BAND against a black-box reference HEVC decoder (which
//! reproduces every frame of the encoder's reconstruction
//! byte-exactly, display order):
//!
//! * an AMP P-GOP over banded content whose motion boundaries sit at
//!   quarter offsets (PART_2NxnU/2NxnD elected on the wire);
//! * a GOP-4 hierarchical-B pyramid over noisy content (out-of-order
//!   coding, positive-RPS slices, PRED_L1/PRED_BI syntax, DPB
//!   reordering, low-delay tail);
//! * the full composition: GOP-8 pyramid x AMP x deblocking + SAO.
//!
//! Re-encoding the same clips must reproduce the golden bytes, and
//! the crate's own decoder must decode them to the encoder's
//! display-order reconstructions. If an intentional encoder change
//! breaks this, regenerate the bytes AND re-run the external
//! cross-decode before updating the pins.

use oxideav_h265::decode_annexb_sequence;
use oxideav_h265::encoder::inter::{FrameRecon, LowDelayPEncoder, YuvFrame};
use oxideav_h265::encoder::loopfilter::LoopFilterCfg;
use oxideav_h265::encoder::pyramid::{encode_pyramid_with, PyramidEncoder};

/// Banded 64x64 clip: three horizontal texture bands split at y = 20
/// and y = 44 (quarter offsets inside CTB rows 1 and 2), the middle
/// band scrolling against the outer ones.
fn banded_clip(n: usize) -> Vec<(Vec<u8>, Vec<u8>, Vec<u8>)> {
    let (w, h) = (64usize, 64usize);
    (0..n)
        .map(|t| {
            let y: Vec<u8> = (0..w * h)
                .map(|i| {
                    let (x, yy) = (i % w, i / w);
                    let (shift, phase) = if yy < 20 {
                        (2 * t, 0usize)
                    } else if yy < 44 {
                        (w - 2 * t, 60)
                    } else {
                        (2 * t + 1, 120)
                    };
                    (((x + shift) * 7 + yy * 3 + phase) % 240) as u8
                })
                .collect();
            (y, vec![110u8; w * h / 4], vec![140u8; w * h / 4])
        })
        .collect()
}

/// Noisy 64x64 clip: a static textured background under small
/// temporally-independent hash noise, plus an 8x8 bright square
/// drifting 1 px per frame.
fn noisy_clip(n: usize) -> Vec<(Vec<u8>, Vec<u8>, Vec<u8>)> {
    let (w, h) = (64usize, 64usize);
    let tex = |u: usize, v: usize| -> i32 { ((u * 3 + v * 5 + (u / 9) * 7) % 200) as i32 };
    let noise = |x: usize, yy: usize, t: usize| -> i32 {
        let h32 = (x
            .wrapping_mul(73_856_093)
            .wrapping_add(yy.wrapping_mul(19_349_663))
            .wrapping_add(t.wrapping_mul(83_492_791))) as u32;
        ((h32 >> 13) % 9) as i32 - 4
    };
    (0..n)
        .map(|t| {
            let y: Vec<u8> = (0..w * h)
                .map(|i| {
                    let (x, yy) = (i % w, i / w);
                    let (sx, sy) = (10 + t, 24);
                    let obj = x >= sx && x < sx + 8 && yy >= sy && yy < sy + 8;
                    let base = tex(x, yy) + if obj { 45 } else { 0 };
                    (base + 8 + noise(x, yy, t)).clamp(0, 255) as u8
                })
                .collect();
            let cb: Vec<u8> = (0..w * h / 4)
                .map(|i| (90 + (i % (w / 2)) % 70) as u8)
                .collect();
            let cr: Vec<u8> = (0..w * h / 4)
                .map(|i| (180 - (i / (w / 2)) % 60) as u8)
                .collect();
            (y, cb, cr)
        })
        .collect()
}

fn as_frames(planes: &[(Vec<u8>, Vec<u8>, Vec<u8>)]) -> Vec<YuvFrame<'_>> {
    planes
        .iter()
        .map(|(y, cb, cr)| YuvFrame { y, cb, cr })
        .collect()
}

/// Encode the AMP P-GOP pin configuration: banded clip, 4 frames,
/// qp 30, AMP, no in-loop filters.
fn encode_amp_pin() -> (Vec<u8>, Vec<FrameRecon>) {
    let planes = banded_clip(4);
    let frames = as_frames(&planes);
    let mut enc = LowDelayPEncoder::new(64, 64, 30, 0)
        .expect("encoder")
        .with_amp(true);
    let mut stream = Vec::new();
    let mut recons = Vec::new();
    for f in &frames {
        let out = enc.encode_frame(f).expect("encode");
        stream.extend_from_slice(&out.au);
        recons.push(out.recon);
    }
    (stream, recons)
}

/// Encode the pyramid pin configuration: noisy clip, 10 frames,
/// qp 27, GOP 4, plain.
fn encode_pyramid_pin() -> (Vec<u8>, Vec<FrameRecon>) {
    let planes = noisy_clip(10);
    let frames = as_frames(&planes);
    let enc = PyramidEncoder::new(64, 64, 27, 4).expect("encoder");
    let out = encode_pyramid_with(enc, &frames).expect("encode");
    (out.stream, out.recon)
}

/// Encode the composition pin: noisy clip, 10 frames, qp 32, GOP-8
/// pyramid, AMP, deblocking + SAO.
fn encode_composition_pin() -> (Vec<u8>, Vec<FrameRecon>) {
    let planes = noisy_clip(10);
    let frames = as_frames(&planes);
    let enc = PyramidEncoder::new(64, 64, 32, 8)
        .expect("encoder")
        .with_amp(true)
        .with_loop_filters(LoopFilterCfg::all());
    let out = encode_pyramid_with(enc, &frames).expect("encode");
    (out.stream, out.recon)
}

fn assert_pin(golden: &[u8], (stream, recons): (Vec<u8>, Vec<FrameRecon>), label: &str) {
    assert_eq!(
        stream, golden,
        "{label}: deterministic encode reproduces the externally validated golden stream"
    );
    let decoded = decode_annexb_sequence(golden).expect("decode");
    assert_eq!(decoded.len(), recons.len(), "{label}: frame count");
    for (i, (dec, rec)) in decoded.iter().zip(recons.iter()).enumerate() {
        let mut expect = rec.y.clone();
        expect.extend_from_slice(&rec.cb);
        expect.extend_from_slice(&rec.cr);
        assert_eq!(
            dec.picture.to_planar_u8().expect("8-bit"),
            expect,
            "{label} frame {i}: decoder output == encoder recon"
        );
    }
}

