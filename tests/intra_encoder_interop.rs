//! Intra-encoder interop pin.
//!
//! The golden access unit below is this crate's deterministic intra
//! encode of a fixed 64x64 test frame at SliceQpY 22, validated OUT OF
//! BAND against a black-box reference HEVC decoder (which reproduces
//! the encoder's reconstruction bit-exactly). Re-encoding the same
//! frame must reproduce the golden bytes, and the crate's own decoder
//! must decode them to the encoder's reconstruction — a three-way
//! (encoder recon / this decoder / external reference decoder)
//! bit-exactness pin. If an intentional encoder change breaks this,
//! regenerate the bytes AND re-run the external cross-decode before
//! updating the pin.

use oxideav_h265::decode_annexb_sequence;
use oxideav_h265::encoder::intra::encode_idr_intra_au;

fn test_frame(w: usize, h: usize) -> (Vec<u8>, Vec<u8>, Vec<u8>) {
    let y: Vec<u8> = (0..w * h)
        .map(|i| {
            let (x, yy) = (i % w, i / w);
            ((x * 3 + yy * 2 + (x * yy / 7) % 31) % 256) as u8
        })
        .collect();
    let cb: Vec<u8> = (0..w * h / 4)
        .map(|i| ((i % (w / 2)) * 4 % 200 + 20) as u8)
        .collect();
    let cr: Vec<u8> = (0..w * h / 4)
        .map(|i| (240 - (i / (w / 2)) * 3 % 200) as u8)
        .collect();
    (y, cb, cr)
}

#[test]
fn golden_intra_stream_is_reproduced_and_decodes_to_recon() {
    let (y, cb, cr) = test_frame(64, 64);
    let enc = encode_idr_intra_au(&y, &cb, &cr, 64, 64, 22).expect("encode");
    assert_eq!(
        enc.au, GOLDEN_QP22_AU,
        "deterministic encode reproduces the externally validated golden AU"
    );
    let frames = decode_annexb_sequence(GOLDEN_QP22_AU).expect("decode");
    assert_eq!(frames.len(), 1);
    let mut recon = enc.recon_y.clone();
    recon.extend_from_slice(&enc.recon_cb);
    recon.extend_from_slice(&enc.recon_cr);
    assert_eq!(
        frames[0].picture.to_planar_u8().expect("8-bit"),
        recon,
        "decoder output == encoder reconstruction"
    );
}

